YEAR = 2026


def parse(block, market):
    out = []
    for line in block.strip().splitlines():
        md, ind, frn = line.split()
        month, day = md.split("/")
        out.append((market, f"{YEAR}-{int(month):02d}-{int(day):02d}", int(ind), int(frn)))
    return out


def main():
    rows = parse(SPOT, "spot") + parse(FUTURES, "futures")
    rows.sort(key=lambda r: (r[0] != "spot", r[1]))
    seen = set()
    for r in rows:
        key = (r[0], r[1])
        assert key not in seen, f"중복: {key}"
        seen.add(key)

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "seed_data.csv")
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["market", "date", "individual", "foreigner"])
        w.writerows(rows)

    print("spot   :", sum(1 for r in rows if r[0] == "spot"), "rows")
    print("futures:", sum(1 for r in rows if r[0] == "futures"), "rows")
    print("saved  :", os.path.normpath(path))


if __name__ == "__main__":
    main()
